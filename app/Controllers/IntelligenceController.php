<?php

declare(strict_types=1);

namespace App\Controllers;

use App\Domain\Intelligence\InsightConfidence;
use App\Domain\Intelligence\InsightLifecycle;
use App\Domain\Intelligence\InsightSignificance;
use App\Domain\Intelligence\InsightTaxonomy;
use App\Domain\Intelligence\IntelligenceService;
use App\Repositories\InsightRepository;
use App\Support\AppException;
use App\Support\Request;
use App\Support\Response;

/**
 * F6 — Deterministic Intelligence API (docs/02 §2 F6, docs/10 D-047).
 *
 * GET /api/v1/intelligence/insights      — strictly read-only listing of
 *                                          persisted insights (validated filters)
 * GET /api/v1/intelligence/insights/{id} — a single persisted insight
 *
 * Both endpoints are read-oriented (docs/06 §3): they validate input and
 * query persisted insights only — no INSERT or UPDATE can occur on a read.
 * Generation is backend-controlled and never triggered by ordinary reads:
 * detection, significance, confidence, deduplication and lifecycle run
 * only through the controlled internal IntelligenceService seam (docs/10
 * D-047), which future ingestion paths invoke. There is no public
 * generation endpoint.
 */
final class IntelligenceController
{
    private const LIMIT_DEFAULT = 50;
    private const LIMIT_MAX = 200;
    private const OFFSET_MAX = 10_000;

    public function __construct(
        private readonly IntelligenceService $service = new IntelligenceService(new InsightRepository())
    ) {
    }

    public function list(Request $request): Response
    {
        $filters = $this->validatedFilters($request);

        $insights = $this->service->listInsights($filters);

        return Response::success([
            'insights' => array_map(
                static fn ($insight): array => $insight->toArray(),
                $insights
            ),
            'count' => count($insights),
            'filters' => $this->echoedFilters($filters),
            'generation' => [
                'mode' => 'DETERMINISTIC_V1',
                'note' => 'Insights are generated by backend-controlled evaluation of F4/F5 evidence and persisted with deduplication. This endpoint is read-only; ordinary reads never create or update insights.',
            ],
        ]);
    }

    public function show(Request $request): Response
    {
        $id = $this->extractId($request->path());
        if ($id === null) {
            throw new AppException('NOT_FOUND', 'Insight not found.', 404);
        }

        $householdId = $this->validatedHouseholdId($request->queryParam('household_id'));

        $insight = $this->service->findInsight($id);
        if ($insight === null) {
            throw new AppException('NOT_FOUND', 'Insight not found.', 404);
        }

        // Ownership boundary: a household-scoped insight is only returned
        // when the request is scoped to the owning household. A mismatch
        // returns 404 (existence is not disclosed).
        if ($insight->householdId() !== null
            && $householdId !== null
            && $insight->householdId() !== $householdId) {
            throw new AppException('NOT_FOUND', 'Insight not found.', 404);
        }

        return Response::success([
            'insight' => $insight->toArray(),
        ]);
    }

    /**
     * @return array<string, mixed>
     */
    private function validatedFilters(Request $request): array
    {
        $filters = [];

        $householdId = $this->validatedHouseholdId($request->queryParam('household_id'));
        if ($householdId !== null) {
            $filters['household_id'] = $householdId;
        }

        $category = $this->validatedEnum($request->queryParam('category'), InsightTaxonomy::CATEGORIES, 'category');
        if ($category !== null) {
            $filters['category'] = $category;
        }

        $type = $this->validatedEnum($request->queryParam('type'), InsightTaxonomy::types(), 'type');
        if ($type !== null) {
            $filters['type'] = $type;
        }

        $significance = $this->validatedEnum($request->queryParam('significance'), InsightSignificance::LEVELS, 'significance');
        if ($significance !== null) {
            $filters['significance'] = $significance;
        }

        $confidence = $this->validatedEnum($request->queryParam('confidence'), InsightConfidence::LEVELS, 'confidence');
        if ($confidence !== null) {
            $filters['confidence'] = $confidence;
        }

        $statusParam = $request->queryParam('status');
        if ($statusParam !== null) {
            $status = InsightLifecycle::normalize($statusParam);
            if ($status === null) {
                throw new AppException(
                    'VALIDATION_ERROR',
                    sprintf('status must be one of: %s.', implode(', ', InsightLifecycle::FILTERABLE_STATES)),
                    422,
                    ['field' => 'status']
                );
            }
            $filters['status'] = $status;
        }

        $periodStart = $this->validatedDate($request->queryParam('period_start'), 'period_start');
        if ($periodStart !== null) {
            $filters['period_start'] = $periodStart;
        }

        $periodEnd = $this->validatedDate($request->queryParam('period_end'), 'period_end');
        if ($periodEnd !== null) {
            $filters['period_end'] = $periodEnd;
        }

        if ($periodStart !== null && $periodEnd !== null && $periodStart > $periodEnd) {
            throw new AppException(
                'VALIDATION_ERROR',
                'period_start must not be after period_end.',
                422,
                ['field' => 'period_start']
            );
        }

        $limitParam = $request->queryParam('limit');
        if ($limitParam !== null) {
            if (!preg_match('/^\d{1,4}$/', $limitParam)) {
                throw new AppException(
                    'VALIDATION_ERROR',
                    'limit must be a positive integer.',
                    422,
                    ['field' => 'limit']
                );
            }
            $limit = (int) $limitParam;
            if ($limit < 1 || $limit > self::LIMIT_MAX) {
                throw new AppException(
                    'VALIDATION_ERROR',
                    sprintf('limit must be between 1 and %d.', self::LIMIT_MAX),
                    422,
                    ['field' => 'limit']
                );
            }
            $filters['limit'] = $limit;
        }

        $offsetParam = $request->queryParam('offset');
        if ($offsetParam !== null) {
            if (!preg_match('/^\d{1,5}$/', $offsetParam)) {
                throw new AppException(
                    'VALIDATION_ERROR',
                    'offset must be a non-negative integer.',
                    422,
                    ['field' => 'offset']
                );
            }
            $offset = (int) $offsetParam;
            if ($offset > self::OFFSET_MAX) {
                throw new AppException(
                    'VALIDATION_ERROR',
                    sprintf('offset must be at most %d.', self::OFFSET_MAX),
                    422,
                    ['field' => 'offset']
                );
            }
            $filters['offset'] = $offset;
        }

        return $filters;
    }

    /**
     * @param array<int, string> $allowed
     */
    private function validatedEnum(?string $raw, array $allowed, string $field): ?string
    {
        if ($raw === null) {
            return null;
        }

        if (!in_array($raw, $allowed, true)) {
            throw new AppException(
                'VALIDATION_ERROR',
                sprintf('%s must be one of: %s.', $field, implode(', ', $allowed)),
                422,
                ['field' => $field]
            );
        }

        return $raw;
    }

    private function validatedHouseholdId(?string $raw): ?string
    {
        if ($raw === null) {
            return null;
        }

        if ($raw === '' || mb_strlen($raw) > 64) {
            throw new AppException(
                'VALIDATION_ERROR',
                'household_id must be a string of at most 64 characters.',
                422,
                ['field' => 'household_id']
            );
        }

        return $raw;
    }

    private function validatedDate(?string $raw, string $field): ?string
    {
        if ($raw === null) {
            return null;
        }

        $date = \DateTimeImmutable::createFromFormat('Y-m-d|', $raw);
        if ($date === false) {
            throw new AppException(
                'VALIDATION_ERROR',
                sprintf('%s must be an ISO 8601 date (Y-m-d).', $field),
                422,
                ['field' => $field]
            );
        }

        return $raw;
    }

    private function extractId(string $path): ?string
    {
        if (preg_match('#^/api/v1/intelligence/insights/([^/]+)$#', $path, $matches) === 1) {
            return $matches[1];
        }

        return null;
    }

    /**
     * @param array<string, mixed> $filters
     * @return array<string, mixed>
     */
    private function echoedFilters(array $filters): array
    {
        return [
            'household_id' => $filters['household_id'] ?? null,
            'category' => $filters['category'] ?? null,
            'type' => $filters['type'] ?? null,
            'significance' => $filters['significance'] ?? null,
            'confidence' => $filters['confidence'] ?? null,
            'status' => $filters['status'] ?? null,
            'period_start' => $filters['period_start'] ?? null,
            'period_end' => $filters['period_end'] ?? null,
            'limit' => $filters['limit'] ?? self::LIMIT_DEFAULT,
            'offset' => $filters['offset'] ?? 0,
        ];
    }
}
